using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.Collections.Specialized;
using System.Globalization;
using System.Linq;
using System.Windows;
using System.Windows.Input;
using System.Windows.Media;
using SWEETs.SweLineStyles.AddIn.Core;

namespace SWEETs.SweLineStyles.AddIn.UI.Controls
{
    public enum ShapeTool { Select, Line, Arc, Circle }

    /// <summary>
    /// Grid editor for a shape. The horizontal axis through the origin is the line the shape sits on; the origin is the
    /// insertion point (the pattern position plus the element's X/Y offset). Every click snaps to the 1/Divisor grid.
    ///
    /// Line: click points; each click adds a segment (Esc, right-click or double-click ends the chain).
    /// Arc: start, end, then a point on the arc. Circle: centre, then a point on the circle.
    /// Select: click a segment, Delete removes it. Wheel zooms about the cursor; right-drag pans.
    /// </summary>
    public sealed class ShapeCanvas : FrameworkElement
    {
        public static readonly DependencyProperty PrimitivesProperty = DependencyProperty.Register(
            nameof(Primitives), typeof(ObservableCollection<ShapePrimitive>), typeof(ShapeCanvas),
            new FrameworkPropertyMetadata(null, FrameworkPropertyMetadataOptions.AffectsRender, OnPrimitivesChanged));
        public static readonly DependencyProperty CompiledProperty = DependencyProperty.Register(
            nameof(Compiled), typeof(IList<ShapePrimitive>), typeof(ShapeCanvas), new FrameworkPropertyMetadata(null, FrameworkPropertyMetadataOptions.AffectsRender));
        public static readonly DependencyProperty DivisorProperty = DependencyProperty.Register(
            nameof(Divisor), typeof(int), typeof(ShapeCanvas), new FrameworkPropertyMetadata(4, FrameworkPropertyMetadataOptions.AffectsRender));
        public static readonly DependencyProperty ExtentProperty = DependencyProperty.Register(
            nameof(Extent), typeof(int), typeof(ShapeCanvas), new FrameworkPropertyMetadata(8, FrameworkPropertyMetadataOptions.AffectsRender, (d, e) => ((ShapeCanvas)d).FitView()));
        public static readonly DependencyProperty ToolProperty = DependencyProperty.Register(
            nameof(Tool), typeof(ShapeTool), typeof(ShapeCanvas), new FrameworkPropertyMetadata(ShapeTool.Line, FrameworkPropertyMetadataOptions.AffectsRender, (d, e) => ((ShapeCanvas)d).CancelDraft()));
        public static readonly DependencyProperty SelectedProperty = DependencyProperty.Register(
            nameof(Selected), typeof(ShapePrimitive), typeof(ShapeCanvas),
            new FrameworkPropertyMetadata(null, FrameworkPropertyMetadataOptions.AffectsRender | FrameworkPropertyMetadataOptions.BindsTwoWayByDefault));
        public static readonly DependencyProperty ShowCompiledProperty = DependencyProperty.Register(
            nameof(ShowCompiled), typeof(bool), typeof(ShapeCanvas), new FrameworkPropertyMetadata(true, FrameworkPropertyMetadataOptions.AffectsRender));
        public static readonly DependencyProperty CursorTextProperty = DependencyProperty.Register(
            nameof(CursorText), typeof(string), typeof(ShapeCanvas), new FrameworkPropertyMetadata("", FrameworkPropertyMetadataOptions.BindsTwoWayByDefault));

        public ObservableCollection<ShapePrimitive> Primitives { get => (ObservableCollection<ShapePrimitive>)GetValue(PrimitivesProperty); set => SetValue(PrimitivesProperty, value); }
        /// <summary>The shape as it will be compiled (decoded from the generated bytes), drawn over the editable geometry.</summary>
        public IList<ShapePrimitive> Compiled { get => (IList<ShapePrimitive>)GetValue(CompiledProperty); set => SetValue(CompiledProperty, value); }
        public int Divisor { get => (int)GetValue(DivisorProperty); set => SetValue(DivisorProperty, value); }
        /// <summary>Half-width of the drawing area in shape units.</summary>
        public int Extent { get => (int)GetValue(ExtentProperty); set => SetValue(ExtentProperty, value); }
        public ShapeTool Tool { get => (ShapeTool)GetValue(ToolProperty); set => SetValue(ToolProperty, value); }
        public ShapePrimitive Selected { get => (ShapePrimitive)GetValue(SelectedProperty); set => SetValue(SelectedProperty, value); }
        public bool ShowCompiled { get => (bool)GetValue(ShowCompiledProperty); set => SetValue(ShowCompiledProperty, value); }
        public string CursorText { get => (string)GetValue(CursorTextProperty); set => SetValue(CursorTextProperty, value); }

        // view: screen = centre + world * zoom (+pan), Y up
        private double _zoom = 40;
        private Vector _pan;
        private bool _fitted;
        private readonly List<Pt> _draft = new List<Pt>();
        private Pt? _hover;
        private Point? _panFrom;
        private bool _panned;

        private static readonly Brush Paper = Freeze(new SolidColorBrush(Colors.White));
        private static readonly Pen MinorPen = Freeze(new Pen(Freeze(new SolidColorBrush(Color.FromRgb(0xEE, 0xF0, 0xF3))), 1));
        private static readonly Pen MajorPen = Freeze(new Pen(Freeze(new SolidColorBrush(Color.FromRgb(0xDA, 0xDD, 0xE3))), 1));
        private static readonly Pen AxisPen = Freeze(new Pen(Freeze(new SolidColorBrush(Color.FromRgb(0x9C, 0xA3, 0xAF))), 1.5) { DashStyle = new DashStyle(new double[] { 6, 4 }, 0) });
        private static readonly Pen InkPen = Freeze(new Pen(Freeze(new SolidColorBrush(Color.FromRgb(0x11, 0x18, 0x27))), 2) { LineJoin = PenLineJoin.Round, StartLineCap = PenLineCap.Round, EndLineCap = PenLineCap.Round });
        private static readonly Pen SelPen = Freeze(new Pen(Freeze(new SolidColorBrush(Color.FromRgb(0x1D, 0x4E, 0xD8))), 3.5) { StartLineCap = PenLineCap.Round, EndLineCap = PenLineCap.Round });
        private static readonly Pen CompiledPen = Freeze(new Pen(Freeze(new SolidColorBrush(Color.FromRgb(0xEA, 0x58, 0x0C))), 1));
        private static readonly Pen DraftPen = Freeze(new Pen(Freeze(new SolidColorBrush(Color.FromRgb(0x1D, 0x4E, 0xD8))), 1.5) { DashStyle = new DashStyle(new double[] { 4, 3 }, 0) });
        private static readonly Pen OriginPen = Freeze(new Pen(Freeze(new SolidColorBrush(Color.FromRgb(0x1D, 0x4E, 0xD8))), 1.5));
        private static readonly Brush LabelBrush = Freeze(new SolidColorBrush(Color.FromRgb(0x6B, 0x72, 0x80)));
        private static T Freeze<T>(T f) where T : Freezable { f.Freeze(); return f; }

        public ShapeCanvas()
        {
            Focusable = true;
            FocusVisualStyle = null;
            ClipToBounds = true;
            SizeChanged += (s, e) => { if (!_fitted) FitView(); };
        }

        private static void OnPrimitivesChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
        {
            var c = (ShapeCanvas)d;
            if (e.OldValue is INotifyCollectionChanged o) o.CollectionChanged -= c.OnCollectionChanged;
            if (e.NewValue is INotifyCollectionChanged n) n.CollectionChanged += c.OnCollectionChanged;
        }

        private void OnCollectionChanged(object sender, NotifyCollectionChangedEventArgs e) => InvalidateVisual();

        public void FitView()
        {
            if (ActualWidth < 10 || ActualHeight < 10) return;
            _zoom = Math.Min(ActualWidth, ActualHeight) / (2.0 * Math.Max(1, Extent) + 1);
            _pan = new Vector();
            _fitted = true;
            InvalidateVisual();
        }

        private Point ToScreen(Pt p) => new Point(ActualWidth / 2 + _pan.X + p.X * _zoom, ActualHeight / 2 + _pan.Y - p.Y * _zoom);
        private Pt ToWorld(Point s) => new Pt((s.X - ActualWidth / 2 - _pan.X) / _zoom, -(s.Y - ActualHeight / 2 - _pan.Y) / _zoom);

        private Pt Snap(Pt p)
        {
            double d = Math.Max(1, Divisor);
            return new Pt(Math.Round(p.X * d) / d, Math.Round(p.Y * d) / d);
        }

        // ------------------------------------------------------------------ input

        protected override void OnMouseLeftButtonDown(MouseButtonEventArgs e)
        {
            Focus();
            var w = Snap(ToWorld(e.GetPosition(this)));
            if (Tool == ShapeTool.Select)
            {
                Selected = HitTest(e.GetPosition(this));
                e.Handled = true;
                return;
            }
            if (e.ClickCount == 2 && Tool == ShapeTool.Line) { CancelDraft(); e.Handled = true; return; }

            _draft.Add(w);
            switch (Tool)
            {
                case ShapeTool.Line:
                    if (_draft.Count == 2)
                    {
                        Add(new LinePrim(_draft[0], _draft[1]));
                        var last = _draft[1];
                        _draft.Clear();
                        _draft.Add(last);   // continue the chain
                    }
                    break;
                case ShapeTool.Arc:
                    if (_draft.Count == 3)
                    {
                        var arc = ArcPrim.FromThreePoints(_draft[0], _draft[2], _draft[1]);
                        if (arc != null) Add(arc);
                        _draft.Clear();
                    }
                    break;
                case ShapeTool.Circle:
                    if (_draft.Count == 2)
                    {
                        double r = _draft[0].DistanceTo(_draft[1]);
                        if (r > 0) Add(ArcPrim.Circle(_draft[0], r));
                        _draft.Clear();
                    }
                    break;
            }
            InvalidateVisual();
            e.Handled = true;
        }

        private void Add(ShapePrimitive p)
        {
            if (p is LinePrim l && l.P1.Near(l.P2)) return;
            Primitives?.Add(p);
        }

        protected override void OnMouseRightButtonDown(MouseButtonEventArgs e)
        {
            _panFrom = e.GetPosition(this);
            _panned = false;
            CaptureMouse();
            e.Handled = true;
        }

        protected override void OnMouseRightButtonUp(MouseButtonEventArgs e)
        {
            ReleaseMouseCapture();
            if (!_panned) CancelDraft();   // a right-click without dragging ends the chain
            _panFrom = null;
            e.Handled = true;
        }

        protected override void OnMouseMove(MouseEventArgs e)
        {
            var pos = e.GetPosition(this);
            if (_panFrom.HasValue && e.RightButton == MouseButtonState.Pressed)
            {
                var delta = pos - _panFrom.Value;
                if (delta.Length > 2) _panned = true;
                _pan += delta;
                _panFrom = pos;
            }
            _hover = Snap(ToWorld(pos));
            CursorText = string.Format(CultureInfo.InvariantCulture, "X {0:0.####}   Y {1:0.####}", _hover.Value.X, _hover.Value.Y);
            InvalidateVisual();
        }

        protected override void OnMouseLeave(MouseEventArgs e)
        {
            _hover = null;
            CursorText = "";
            InvalidateVisual();
        }

        protected override void OnMouseWheel(MouseWheelEventArgs e)
        {
            var pos = e.GetPosition(this);
            var before = ToWorld(pos);
            _zoom = Math.Max(4, Math.Min(2000, _zoom * (e.Delta > 0 ? 1.2 : 1 / 1.2)));
            var after = ToScreen(before);
            _pan += pos - after;
            InvalidateVisual();
            e.Handled = true;
        }

        protected override void OnKeyDown(KeyEventArgs e)
        {
            if (e.Key == Key.Escape) { CancelDraft(); Selected = null; e.Handled = true; }
            else if ((e.Key == Key.Delete || e.Key == Key.Back) && Selected != null && Primitives != null)
            {
                Primitives.Remove(Selected);
                Selected = null;
                e.Handled = true;
            }
        }

        public void CancelDraft()
        {
            _draft.Clear();
            InvalidateVisual();
        }

        private ShapePrimitive HitTest(Point screen)
        {
            if (Primitives == null) return null;
            var w = ToWorld(screen);
            double tol = 6 / _zoom;
            return Primitives.Select(p => (p, d: p.DistanceTo(w))).Where(x => x.d <= tol).OrderBy(x => x.d).Select(x => x.p).FirstOrDefault();
        }

        // ------------------------------------------------------------------ render

        protected override void OnRender(DrawingContext dc)
        {
            double w = ActualWidth, h = ActualHeight;
            dc.DrawRectangle(Paper, null, new Rect(0, 0, w, h));
            if (w < 10 || h < 10) return;

            var tl = ToWorld(new Point(0, 0));
            var br = ToWorld(new Point(w, h));
            double minor = 1.0 / Math.Max(1, Divisor);
            if (minor * _zoom >= 6) DrawGrid(dc, minor, MinorPen, tl, br);
            int majorStep = _zoom >= 6 ? 1 : (int)Math.Ceiling(6 / _zoom);
            DrawGrid(dc, majorStep, MajorPen, tl, br);

            // Line axis and insertion point
            var o = ToScreen(new Pt(0, 0));
            dc.DrawLine(AxisPen, new Point(0, o.Y), new Point(w, o.Y));
            dc.DrawEllipse(null, OriginPen, o, 5, 5);
            dc.DrawLine(OriginPen, new Point(o.X - 9, o.Y), new Point(o.X + 9, o.Y));
            dc.DrawLine(OriginPen, new Point(o.X, o.Y - 9), new Point(o.X, o.Y + 9));
            Label(dc, "insertion point", new Point(o.X + 8, o.Y + 4));
            Label(dc, "line axis", new Point(6, o.Y - 16));

            if (Primitives != null)
                foreach (var p in Primitives) Draw(dc, p, ReferenceEquals(p, Selected) ? SelPen : InkPen);
            if (ShowCompiled && Compiled != null)
                foreach (var p in Compiled) Draw(dc, p, CompiledPen);

            // Draft (rubber band)
            if (_draft.Count > 0 && _hover.HasValue)
            {
                var hv = _hover.Value;
                switch (Tool)
                {
                    case ShapeTool.Line: Draw(dc, new LinePrim(_draft[_draft.Count - 1], hv), DraftPen); break;
                    case ShapeTool.Circle: Draw(dc, ArcPrim.Circle(_draft[0], _draft[0].DistanceTo(hv)), DraftPen); break;
                    case ShapeTool.Arc:
                        if (_draft.Count == 1) Draw(dc, new LinePrim(_draft[0], hv), DraftPen);
                        else
                        {
                            var arc = ArcPrim.FromThreePoints(_draft[0], hv, _draft[1]);
                            Draw(dc, arc ?? (ShapePrimitive)new LinePrim(_draft[0], _draft[1]), DraftPen);
                        }
                        break;
                }
                foreach (var d in _draft) dc.DrawRectangle(SelPen.Brush, null, Square(ToScreen(d), 3));
            }
            if (_hover.HasValue && Tool != ShapeTool.Select)
                dc.DrawRectangle(null, OriginPen, Square(ToScreen(_hover.Value), 4));
        }

        private static Rect Square(Point c, double r) => new Rect(c.X - r, c.Y - r, 2 * r, 2 * r);

        private void DrawGrid(DrawingContext dc, double step, Pen pen, Pt tl, Pt br)
        {
            double x0 = Math.Floor(tl.X / step) * step, x1 = br.X, y0 = Math.Floor(br.Y / step) * step, y1 = tl.Y;
            int guard = 0;
            for (double x = x0; x <= x1 && guard++ < 2000; x += step)
            {
                double sx = Math.Round(ToScreen(new Pt(x, 0)).X) + 0.5;
                dc.DrawLine(pen, new Point(sx, 0), new Point(sx, ActualHeight));
            }
            guard = 0;
            for (double y = y0; y <= y1 && guard++ < 2000; y += step)
            {
                double sy = Math.Round(ToScreen(new Pt(0, y)).Y) + 0.5;
                dc.DrawLine(pen, new Point(0, sy), new Point(ActualWidth, sy));
            }
        }

        private void Draw(DrawingContext dc, ShapePrimitive p, Pen pen)
        {
            var polys = new List<Pt[]>();
            p.Tessellate(polys, 3);
            var geo = new StreamGeometry();
            using (var g = geo.Open())
                foreach (var poly in polys.Where(x => x.Length > 1))
                {
                    g.BeginFigure(ToScreen(poly[0]), false, false);
                    g.PolyLineTo(poly.Skip(1).Select(ToScreen).ToList(), true, true);
                }
            geo.Freeze();
            dc.DrawGeometry(null, pen, geo);
        }

        private void Label(DrawingContext dc, string text, Point at)
        {
            var ft = new FormattedText(text, CultureInfo.InvariantCulture, FlowDirection.LeftToRight, new Typeface("Segoe UI"), 11, LabelBrush,
                VisualTreeHelper.GetDpi(this).PixelsPerDip);
            dc.DrawText(ft, at);
        }
    }
}
